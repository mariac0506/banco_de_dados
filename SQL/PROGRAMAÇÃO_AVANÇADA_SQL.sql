/*VIEW:
-VIEWS SÃO PSEUDO-TABELAS QUE GRAVAM SQL GRANDES PARA SEREM EXECUTADOS EM DIVERSAS PARTES DO CODIGO, SEM PRECISAR REESCREVER O SELECT */

-- CRIAR UMA VIEW PARA RETORNAR OS FUNCIONARIOS E OS SEUS SUPERMERCADOS
CREATE OR REPLACE VIEW VW_FUNCIONARIOS_SUPERMERCADOS AS
SELECT	F.FUN_CPF AS "CPF",
		F.FUN_NOME AS "NOME",
		F.FUN_DATA_NASCIMENTO AS "DATA DE NASCIMENTO",
        F.FUN_TELEFONE AS "TELEFONE",
        F.FUN_EMAIL AS "EMAIL",
        F.FUN_CARTEIRA_TRABALHO AS "CARTEIRA DE TRABALHO",
        F.FUN_BANCO_AGENCIA AS "AGENCIA DO BANCO",
        F.FUN_BANCO_CONTA AS "CONTA DO BANCO",
        F.FUN_DATA_ADMISSAO AS "DATA DE ADMISSAO",
        F.FUN_JORNADA_TRABALHO AS "JORNADA DE TRABALHO",
        S.SUP_RAZAO_SOCIAL AS "SUPERMERCADO QUE TRABALHA"
FROM FUNCIONARIO F
JOIN SUPERMERCADO S ON (S.SUP_CNPJ = F.FK_SUP_CNPJ);

SELECT * FROM VW_FUNCIONARIOS_SUPERMERCADOS;

SELECT * 
FROM 	VW_FUNCIONARIOS_SUPERMERCADOS
WHERE	UPPER(NOME) LIKE '%RAFAEL%';

/* VIEW -  1.PRODUTOS PROXIMOS DA VALIDADE */
CREATE OR REPLACE VIEW VW_PRODUTOS_VENCIMENTO AS
SELECT 	PRO_NOME AS "NOME",
		PRO_PRECO AS "PREÇO",
        PRO_QUANTIDADE AS "QUANTIDADE DE PRODUTO",
        PRO_DATA_VALIDADE AS "DATA VALIDADE",
        DATEDIFF(PRO_DATA_VALIDADE, CURDATE()) AS "DIAS DE VENCIMENTO"
FROM    PRODUTO
WHERE   DATEDIFF(PRO_DATA_VALIDADE, CURDATE()) <=15;

SELECT * FROM VW_PRODUTOS_VENCIMENTO;


